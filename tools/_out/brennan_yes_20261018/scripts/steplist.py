"""steplist.py: one download list of every Brennan 3D file (STEP) the project still needs, by priority. Reads ../steps_needed.csv,
../brennan_rows.csv (enumerate.py); writes ../3D_FILES_NEEDED.md."""
import csv, os, re, collections

ROOT = r'C:\Users\sudha\OneDrive\Desktop\OMi_Handoff'
OUT = os.path.join(ROOT, r'tools\_out\brennan_yes_20261018')
S = list(csv.DictReader(open(os.path.join(OUT, 'steps_needed.csv'), encoding='utf-8')))
B = list(csv.DictReader(open(os.path.join(OUT, 'brennan_rows.csv'), encoding='utf-8')))
have = {f[8:-4].upper() for f in os.listdir(os.path.join(ROOT, '09_STEP_FILES')) if f.upper().startswith('BRENNAN_')}
# Brennan has no file for these (user, 2026-10-02; PROJECT_STATUS s3 item 2) - do not ask for them again
NOFILE = set('''1405-20-24 2403-06-02 2502-20-16-FG 2705-04-02 6500-20-16-FG 6500-24-20-FG 6500-32-24-FG 6501-16-12-FG 6502-06-04-FG
6502-12-10-FG 6802-04-02-NWO-FG 1602-08-08-08-FG 1803-08-08-FG 2406-06-12 5404-L-04X2.000 5404-N-06X2.000 5404-R-04-04-047 6425-08-08
6500-04-02-FG 6502-04-02-FG 6505-04-02 6566-06-06-FG'''.split()) | {'2700-04-02', '2700-08-06', '2700-10-08', '2700-12-10'}
OMI_DRAWN = {'1405-04-06', '1405-08-12', '1502-06-06-FG', '1502-12-08-FG', '1502-12-12-FG', '1502-20-20-FG', '1502-24-24-FG', '1502-32-32-FG',
             '1504-20-20-FG', '1602-02-02-02-FG', '1602-04-04-04-FG', '1602-08-08-08-FG', '1602-16-16-16-FG', '1602-20-20-20-FG'}

dim_only = {b['config'] for b in B if b['how'] == '3D file'}      # Brennan 3D file = the only dimension source of these rows
use = collections.defaultdict(lambda: dict(rows=set(), tables=set(), dims=False))
for s in S:
    st = s['step'].strip()
    if not re.match(r'^\d{4}', st) or '(' in st or ' ' in st:
        continue            # placeholders ("6801-L pilot (coming)", "(STEP, part not named)", ...)
    u = use[st]; u['rows'].add(s['config']); u['tables'].add(s['table'])
    if s['config'] in dim_only:
        u['dims'] = True
nofile = sorted(k for k in use if k in NOFILE)
need = {k: v for k, v in use.items() if k.upper() not in have and k not in NOFILE
        and not (k in OMI_DRAWN and k[:4] in ('1405', '1502'))}   # 1405 / 1502: dimensions from OMi, shape already in the generator
p1 = sorted(k for k, v in need.items() if v['dims'])
p2 = sorted(k for k, v in need.items() if not v['dims'])

L = ['# Brennan 3D files (STEP) still needed - 2026-10-18', '',
     'Save each as `09_STEP_FILES/BRENNAN_<part number>.stp` (Brennan part number = OMi part number). Nothing here is in 09_STEP_FILES yet.',
     'Generated by `tools/_out/brennan_yes_20261018/scripts/steplist.py` from the row gates (unblock_20261008/rows.csv) - re-run after downloading.', '',
     '## 1. First: the ORFS pilots (9) - `tools/_out/orfs_modeltype_20261016/STEPS_NEEDED.txt` part 1',
     'FS2403-08-08, FS6500-08-08-FG, FS2701-08-08-FG, FS6400-08-08-O, FS6801-08-08-NWO-FG, FS0318-08, FS0319-08, FS0306-08, FS2406-08-06.',
     'Optional with them: the Air-Way 3D models A1-A9 of that file (3DContentCentral; your sign-in), saved as `AIRWAY_<item>.stp`.',
     'After the pilots pass: 8 per-dash files E1-E8 and 15 family pilots F1-F15 (same file).', '',
     '## 1b. Tap drill -24 / -32 (question A9, user: "wait for a brennan step") - 2 files',
     '5405-24-24, 5405-32-32 (female pipe port of each size; see `a9_tapdrill/README.md`).', '',
     f'## 2. Parts whose ONLY dimension source is their Brennan 3D file ({len(p1)} files) - opened by today\'s Brennan decision', '']
for k in p1:
    L.append(f'- {k}  ({", ".join(sorted(need[k]["tables"]))})')
L += ['', f'## 3. Shape files for parts that have dimensions but need the forged body / end shape ({len(p2)} files)', '',
      'Grouped by family; one file per line. (*) = OMi sent a drawing for this part on 2026-10-18 (dimensions done; the file gives the shape).', '']
by = collections.defaultdict(list)
for k in p2:
    by[k.split('-')[0]].append(k + (' (*)' if k in OMI_DRAWN else ''))
for fam in sorted(by):
    L.append(f'- **{fam}**: ' + ', '.join(by[fam]))
L += ['', '## 4. Other files asked for earlier',
      '- Code 62 flange heads -12 / -16 / -20 / -24 / -32 (e.g. 1824-12, -16, -20, -24, -32 or 1800-NN-NN) - bent-tube 1803 / 1804 and FS1800 later.',
      '- V0318-08 and V0319-08 (flareless nut + sleeve shape).',
      '- 1704-16-16, 1803-16-16, 6701-08-08 (bent-tube shape checks).',
      '- Still promised from 2026-10-02: the 6801-L / -LL, 6805, 6806, 6807, 6809, 6810, 6815, 6832, 6835, 6901, 6902 pilots (15 files).', '',
      f'## Not to ask for: Brennan has no file ({len(nofile)} referenced here): ' + ', '.join(nofile)]
open(os.path.join(OUT, '3D_FILES_NEEDED.md'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print('priority-2 (dimension) files', len(p1), '| shape files', len(p2), '| no-file', len(nofile))
