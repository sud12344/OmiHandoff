"""regen_all.py (group B, 2026-10-21): regenerate EVERY generator root with the old and the new toolset and diff.
  non-FS: old = tools/_out/airway_first_20261020/tools_af + OMI_ROOT tools/_out/brennancad_20261021/stage
          new = groupB_20261021/tools_af                  + OMI_ROOT groupB_20261021/stage
  FS:     old = tools/_out/orfs_gen_20261020/tools  OMI_ROOT repo, OMI_REV_EXTRA brennancad stage/orfs_tables
          new = groupB_20261021/tools_fs            OMI_ROOT repo, OMI_REV_EXTRA groupB stage/orfs_tables
  rings:  gen_ring.py of the FS toolset (its SPEC roots: 4000 = 4000 + 4001 + FS4000 (+ 4005 new) folded, 0319T); GR_REV = the staged
          newtypes_20261014 review tables (4000 / 4001, as the ORFS README runs it); new: OMI_REV_EXTRA also the group B 04 stage (4005)
Writes regen/{old,new}/<set>/..., regen/cmp.txt: per root configurations old / new, NEW, LOST, changed configurations, macro identical.
usage: python regen_all.py [root ...]   (default: every root of both toolsets)"""
import os, sys, re, subprocess, openpyxl, json

H = os.path.dirname(os.path.abspath(__file__)); A = os.path.dirname(H)
ROOT = os.path.normpath(os.path.join(A, '..', '..', '..'))
J = lambda *a: os.path.join(ROOT, *a)
SETS = {
    'af': dict(old=J('tools', '_out', 'airway_first_20261020', 'tools_af'), new=os.path.join(A, 'tools_af'),
               env_old=dict(OMI_ROOT=J('tools', '_out', 'brennancad_20261021', 'stage')), env_new=dict(OMI_ROOT=os.path.join(A, 'stage'))),
    'fs': dict(old=J('tools', '_out', 'orfs_gen_20261020', 'tools'), new=os.path.join(A, 'tools_fs'),
               env_old=dict(OMI_ROOT=ROOT, OMI_REV_EXTRA=J('tools', '_out', 'brennancad_20261021', 'stage', 'orfs_tables'),
                            GR_REV=J('tools', '_out', 'newtypes_20261014', 'review_tables')),
               env_new=dict(OMI_ROOT=ROOT, OMI_REV_EXTRA=os.pathsep.join([os.path.join(A, 'stage', 'orfs_tables'), os.path.join(A, 'stage', '04_DESIGN_TABLES')]),
                            GR_REV=J('tools', '_out', 'newtypes_20261014', 'review_tables'))),
}
OUT = os.path.join(A, 'regen')


def spec_roots(tools, gen, env_extra):
    """every SPEC root of a generator (imported in a child process: the FS roots are added by SPEC.update / loops)"""
    if not os.path.exists(os.path.join(tools, 'generators', gen)): return []
    code = ('import sys, os; sys.path.insert(0, sys.argv[1]); sys.path.insert(0, os.path.dirname(sys.argv[1])); '
            'import importlib; m = importlib.import_module(sys.argv[2]); print("\\n".join(m.SPEC))')
    env = dict(os.environ, GS_OUT=os.path.join(OUT, 'scratch_import'), GT_OUT=os.path.join(OUT, 'scratch_import'),
               GR_OUT=os.path.join(OUT, 'scratch_import'), **env_extra)
    p = subprocess.run([sys.executable, '-I', '-B', '-c', code, os.path.join(tools, 'generators'), gen[:-3]], env=env, capture_output=True, text=True)
    if p.returncode: raise SystemExit(f'cannot import {tools} {gen}: {p.stderr[-2000:]}')
    return [x for x in p.stdout.split() if x]


def run(tools, gen, root, out, env_extra):
    os.makedirs(out, exist_ok=True)
    env = dict(os.environ, GS_OUT=out, GT_OUT=out, GR_OUT=out, **env_extra)
    p = subprocess.run([sys.executable, '-I', '-B', os.path.join(tools, 'generators', gen), root], env=env, capture_output=True, text=True,
                       cwd=out)
    open(os.path.join(out, f'{root}_stdout.txt'), 'w', encoding='utf-8').write(p.stdout + '\n--- stderr ---\n' + p.stderr)
    return p.returncode


def load(p):
    if not os.path.exists(p): return {}
    rs = list(openpyxl.load_workbook(p, read_only=True, data_only=True).worksheets[0].iter_rows(values_only=True))
    hdr = [i for i, r in enumerate(rs) if r and r[0] is None and any(r)]
    hi = hdr[0] if hdr else 0; h = rs[hi]
    return {r[0]: dict(zip(h, r)) for r in rs[hi + 1:] if r and r[0]}


def txt(p):
    return open(p, encoding='utf-8', errors='replace').read().replace('\r\n', '\n') if os.path.exists(p) else None


want = set(sys.argv[1:])
lines = []
for s, cfg in SETS.items():
    jobs = []
    for gen in ('gen_straight2.py', 'gen_tee.py', 'gen_ring.py'):
        ro = spec_roots(cfg['old'], gen, cfg['env_old']); rn = spec_roots(cfg['new'], gen, cfg['env_new'])
        for r in dict.fromkeys(ro + rn):
            if s == 'af' and r.startswith('FS'): continue          # FS roots are generated by the FS toolset only
            if s == 'fs' and not r.startswith('FS') and gen != 'gen_ring.py': continue   # non-FS roots: the af toolset
            if want and r not in want: continue
            jobs.append((gen, r, r in ro, r in rn))
    for gen, r, ino, inn in jobs:
        o = os.path.join(OUT, 'old', s, r); n = os.path.join(OUT, 'new', s, r)
        rc_o = run(cfg['old'], gen, r, o, cfg['env_old']) if ino else None
        rc_n = run(cfg['new'], gen, r, n, cfg['env_new']) if inn else None
        tabs_o = sorted(f for f in os.listdir(o) if f.endswith('_SW2.xlsx')) if ino else []
        tabs_n = sorted(f for f in os.listdir(n) if f.endswith('_SW2.xlsx')) if inn else []
        for t in sorted(set(tabs_o) | set(tabs_n)):
            mr = t[len('DesignTable_'):-len('_SW2.xlsx')]
            c = load(os.path.join(o, t)) if ino else {}; d = load(os.path.join(n, t))
            new = sorted(set(d) - set(c)); lost = sorted(set(c) - set(d)); chg = sorted(k for k in set(c) & set(d) if c[k] != d[k])
            mo = txt(os.path.join(o, f'Build_{mr}_MASTER.bas')); mn = txt(os.path.join(n, f'Build_{mr}_MASTER.bas'))
            same = 'n/a' if mo is None or mn is None else ('identical' if mo == mn else 'DIFFERS')
            lines.append(f'{s}:{gen[:-3]:13} {mr:9} rc {rc_o}/{rc_n} | configs old {len(c):3d} new {len(d):3d} | NEW {len(new)} | LOST {len(lost)} {lost} | '
                         f'changed {len(chg)} {chg[:8]} | macro {same}' + (f' | new: {" ".join(new)}' if new else ''))
            print(lines[-1], flush=True)
        if not tabs_o and not tabs_n:
            lines.append(f'{s}:{gen[:-3]:13} {r:9} rc {rc_o}/{rc_n} | no SW2 table either side'); print(lines[-1], flush=True)
tag = '_'.join(sorted(want)) if want else 'all'
open(os.path.join(OUT, f'cmp_{tag}.txt' if want else 'cmp.txt'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
